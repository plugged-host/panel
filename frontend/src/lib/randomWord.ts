/** A word other than `current`, so asking again always changes the name. */
export function randomWord(current?: string): string {
  const words = current ? RANDOM_WORDS.filter((word) => word !== current) : RANDOM_WORDS;

  return words[Math.floor(Math.random() * words.length)];
}
